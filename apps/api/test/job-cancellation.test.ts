test('cancelamento por requerimento encerra a inspeção, preserva o original e libera a execução',async()=>{
 let entered!:()=>void,release!:()=>void;const started=new Promise<void>(r=>entered=r),gate=new Promise<void>(r=>release=r);
 behavior=async o=>{entered();await new Promise<void>((resolve,reject)=>{o.signal?.addEventListener('abort',()=>reject(new Error('worker aborted')),{once:true});gate.then(()=>resolve(),()=>resolve());});return report(o);};
 const pending=app.inject({method:'POST',url:'/api/imports',headers,payload:payload as any});
 await started;
 const [job]=await db.query("SELECT j.id FROM jobs j JOIN import_runs r ON r.id=j.id WHERE j.organization_id=$1 AND j.status='running' ORDER BY j.created_at DESC LIMIT 1",[org]);
 assert.ok(job,'a inspeção em andamento não foi registrada');
 const cancel=await app.inject({method:'POST',url:`/api/jobs/${job.id}/cancel`,headers});
 assert.equal(cancel.statusCode,200,cancel.body);
 assert.equal(cancel.json().status,'cancelling');
 release();
 const result=await pending;
 assert.equal(result.statusCode,409,result.body);
 assert.equal(result.json().error.code,'IMPORT_CANCELLED');
 const [row]=await db.query('SELECT j.status,j.cancel_requested_at AS "cancelRequestedAt",j.cancel_requested_by AS "cancelRequestedBy",r.error_code AS "errorCode",r.evidence_id AS "evidenceId" FROM jobs j JOIN import_runs r ON r.id=j.id WHERE j.id=$1',[job.id]);
 assert.equal(row.status,'cancelled');
 assert.equal(row.errorCode,'IMPORT_CANCELLED');
 assert.ok(row.cancelRequestedAt,'o pedido de cancelamento não foi registrado');
 assert.ok(row.cancelRequestedBy,'o requerente do cancelamento não foi registrado');
 assert.equal((await db.query('SELECT * FROM import_execution_lock')).length,0);
 const evidence=await app.inject({url:`/api/evidence/${row.evidenceId}`,headers});
 assert.equal(evidence.statusCode,200,evidence.body);
 assert.equal(evidence.json().integrityVerified,true,'o original cancelado deixou de ser verificável');
 const events=(await db.query('SELECT action FROM audit_events WHERE resource_id=$1 ORDER BY created_at',[job.id])).map((e:any)=>e.action);
 assert.ok(events.includes('job.cancel_requested'),'o pedido de cancelamento não foi auditado');
 assert.ok(events.includes('import.cancelled'),'o cancelamento não foi auditado');
});

